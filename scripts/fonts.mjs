// Generates @font-face rules for any licensed display font dropped into public/fonts/display/.
// Runs automatically before `dev` and `build`. No files → empty stylesheet (fallback fonts apply).
import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "public/fonts/display");
const out = join(process.cwd(), "src/styles/display-font.generated.css");
mkdirSync(join(process.cwd(), "src/styles"), { recursive: true });

const weights = [
  [/thin|hairline/i, 100], [/extralight|ultralight/i, 200], [/light/i, 300],
  [/semibold|demibold/i, 600], [/extrabold|ultrabold/i, 800], [/black|heavy/i, 900],
  [/bold/i, 700], [/medium/i, 500], [/regular|book|normal/i, 400],
];
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".woff2")) : [];
// Georgian (Mkhedruli, Mtavruli, Nuskhuri/Asomtavruli) only
const range = "U+10A0-10FF, U+1C90-1CBF, U+2D00-2D2F";

const css = files
  .map((file) => {
    const weight = weights.find(([re]) => re.test(file))?.[1] ?? 400;
    const style = /italic/i.test(file) ? "italic" : "normal";
    return `@font-face {\n  font-family: "Royale Display";\n  src: url("/fonts/display/${file}") format("woff2");\n  font-weight: ${weight};\n  font-style: ${style};\n  font-display: swap;\n  unicode-range: ${range};\n}`;
  })
  .join("\n\n");

writeFileSync(out, `/* AUTO-GENERATED by scripts/fonts.mjs — do not edit. */\n${css}\n`);
console.log(files.length ? `fonts: ${files.length} display font file(s) registered` : "fonts: no custom display font, using fallback");
